cities = ("Chennai", "Mumbai", "Delhi", "Chennai", "Pune")

# 1. Print the first element.
print(cities[0])
# 2. Print the last element.
print(cities[-1])
# 3. Print the total number of elements.
print(len(cities))
# 4. Count how many times "Chennai" appears.
print(cities.count("Chennai"))
# 5. Find the index of "Delhi".
print(cities.index("Delhi"))
# 6. Print elements from index 1 to 3 using slicing.
print(cities[1:4])